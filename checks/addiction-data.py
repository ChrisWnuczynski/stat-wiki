D=np.loadtxt(StringIO(COUNTS),delimiter=",")
X=np.c_[np.ones(len(D)),D[:,:3]]
Y=D[:,3:];n=Y.sum(axis=1)
assert int(n.sum())==682
def fg(v):
    eta=np.c_[np.zeros(len(D)),X@v.reshape(4,2)]
    p=softmax(eta,axis=1)
    return np.sum(n*logsumexp(eta,axis=1)-(Y*eta).sum(axis=1)),(X.T@(n[:,None]*p[:,1:]-Y[:,1:])).ravel()
fit=minimize(fg,np.zeros(8),jac=True,method="BFGS",options={"gtol":1e-7,"maxiter":1000})
assert fit.success or np.max(np.abs(fg(fit.x)[1]))<1e-5
B=fit.x.reshape(4,2)
expected=np.array([[-1.1607,-2.0156],[.4366,.2879],[.0299,.0421],[1.6220,1.0673]])
assert np.allclose(B,expected,atol=0.00005)
p=softmax(np.c_[np.zeros(len(D)),X@B],axis=1)
H=sum(ni*np.kron(np.outer(x,x),np.diag(pi[1:])-np.outer(pi[1:],pi[1:])) for ni,x,pi in zip(n,X,p))
se=np.sqrt(np.diag(np.linalg.inv(H))).reshape(4,2)
assert np.allclose(B/se,[[-4.37,-6.55],[2.25,1.30],[4.80,6.17],[6.40,3.69]],atol=.005)
for academic,target in [(0,[.363147,.376195,.260658]),(1,[.120018,.629511,.250471])]:
    eta=np.r_[0,np.array([1,0,40,academic])@expected]
    assert np.allclose(softmax(eta),target,atol=5e-7)
assert abs(np.exp(1.6220)-5.063207)<5e-7
assert abs(np.exp(1.0673-1.6220)-.574245)<5e-7
assert np.allclose(softmax([0,0,0]),[1/3]*3)
assert abs(np.exp(.8)-2.225540928492468)<1e-13
assert abs(expit(-.6)-.35434369377420455)<1e-13
assert abs(np.exp(10*.04618)-1.586928)<5e-7
assert np.allclose(np.exp(10*np.array([.02484,.06851])),[1.281973,1.983970],atol=5e-7)
assert np.allclose(expit(-3.70568+.04618*np.array([60,70])),[.281936,.383888],atol=5e-7)
